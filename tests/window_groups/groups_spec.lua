		vim.api.nvim_buf_delete(buf1, { force = true })
		vim.api.nvim_buf_delete(buf2, { force = true })
	end)

	it("returns nil for empty group", function()
		local win = vim.api.nvim_get_current_win()
		vim.api.nvim_win_set_var(win, "group_bufs", {})
		assert.is_nil(wg.last_buf(win))
	end)
end)

describe("close_buf() with unsaved changes", function()
	it("keeps a modified buf in its group and on screen", function()
		local win = vim.api.nvim_get_current_win()
		local clean = vim.api.nvim_create_buf(true, false)
		local dirty = vim.api.nvim_create_buf(true, false)
		vim.api.nvim_buf_set_lines(dirty, 0, -1, false, { "unsaved" })
		vim.api.nvim_win_set_buf(win, dirty)
		vim.api.nvim_win_set_var(win, "group_bufs", { clean, dirty })
		wg.close_buf()
		assert.is_true(vim.api.nvim_buf_is_valid(dirty))
		assert.same({ clean, dirty }, wg.list(win))
		assert.equals(dirty, vim.api.nvim_win_get_buf(win))
		vim.api.nvim_buf_delete(clean, { force = true })
		vim.api.nvim_buf_delete(dirty, { force = true })
	end)
end)

describe("close_group() with unsaved changes", function()
	it("closes clean bufs, keeps modified ones in the group and the window open", function()
		vim.cmd("vsplit")
		local win = vim.api.nvim_get_current_win()
		local clean = vim.api.nvim_create_buf(true, false)
		local dirty = vim.api.nvim_create_buf(true, false)
		vim.api.nvim_buf_set_lines(dirty, 0, -1, false, { "unsaved" })
		vim.api.nvim_win_set_buf(win, clean)
		vim.api.nvim_win_set_var(win, "group_bufs", { clean, dirty })
		wg.close_group()
		assert.is_true(vim.api.nvim_win_is_valid(win))
		assert.is_false(vim.api.nvim_buf_is_valid(clean))
		assert.same({ dirty }, wg.list(win))
		assert.equals(dirty, vim.api.nvim_win_get_buf(win))
		vim.api.nvim_buf_delete(dirty, { force = true })
		vim.cmd("only")
	end)
end)

describe("highlights", function()
	it("restores fallbacks after a colorscheme clears them", function()
		vim.api.nvim_set_hl(0, "TabLineSel", { bg = "#123456" })
		vim.cmd("doautocmd ColorScheme")
		vim.cmd("highlight clear")
		vim.api.nvim_set_hl(0, "TabLineSel", { bg = "#654321" })
		vim.cmd("doautocmd ColorScheme")
		local hl = vim.api.nvim_get_hl(0, { name = "GroupsActive", link = false })
		assert.equals(tonumber("654321", 16), hl.bg)
	end)

	it("keeps groups a colorscheme defines itself", function()
		vim.cmd("highlight clear")
		vim.api.nvim_set_hl(0, "GroupsActive", { bg = "#abcdef" })
		vim.cmd("doautocmd ColorScheme")
		local hl = vim.api.nvim_get_hl(0, { name = "GroupsActive", link = false })
		assert.equals(tonumber("abcdef", 16), hl.bg)
	end)
end)

describe("winbar option", function()
	local function local_winbar(win)
		return vim.api.nvim_get_option_value("winbar", { win = win, scope = "local" })
	end

	it("is empty for windows without a group", function()
		vim.cmd("botright new")
		local win = vim.api.nvim_get_current_win()
		vim.bo.buftype = "nofile"
		vim.cmd("doautocmd BufWinEnter")
		assert.equals("", vim.o.winbar)
		assert.equals("", local_winbar(win))
		vim.cmd("close")
	end)

	it("renders the group strip in editor windows", function()
		vim.cmd("botright vnew")
		local win = vim.api.nvim_get_current_win()
		vim.bo.buflisted = true
		vim.cmd("doautocmd BufWinEnter")
		assert.is_truthy(local_winbar(win):find("window_groups.winbar", 1, true))
		vim.cmd("close")
	end)
end)

describe("move_buf() of the last buffer in a group", function()
	it("closes the emptied source window", function()
		vim.cmd("only")
		local left = vim.api.nvim_get_current_win()
		local a = vim.api.nvim_create_buf(true, false)
		local b = vim.api.nvim_create_buf(true, false)
		vim.api.nvim_win_set_buf(left, a)
		vim.api.nvim_win_set_var(left, "group_bufs", { a })
		vim.cmd("rightbelow vsplit")
		local right = vim.api.nvim_get_current_win()
		vim.api.nvim_win_set_buf(right, b)
		vim.api.nvim_win_set_var(right, "group_bufs", { b })
		vim.api.nvim_set_current_win(left)
		local bufs_before = #vim.api.nvim_list_bufs()
		wg.move_buf("right")
		assert.is_false(vim.api.nvim_win_is_valid(left))
		assert.same({ b, a }, wg.list(right))
		assert.equals(bufs_before, #vim.api.nvim_list_bufs())
		vim.api.nvim_buf_delete(a, { force = true })
		vim.api.nvim_buf_delete(b, { force = true })
	end)
end)

describe("opening a buffer owned by another window", function()
	it("focuses the owner and shows the buffer there", function()
		vim.cmd("only")
		local left = vim.api.nvim_get_current_win()
		local a = vim.api.nvim_create_buf(true, false)
		local b = vim.api.nvim_create_buf(true, false)
		local c = vim.api.nvim_create_buf(true, false)
		vim.api.nvim_win_set_buf(left, a)
		vim.api.nvim_win_set_var(left, "group_bufs", { a, b })
		vim.cmd("rightbelow vsplit")
		local right = vim.api.nvim_get_current_win()
		vim.api.nvim_win_set_buf(right, c)
		vim.api.nvim_win_set_var(right, "group_bufs", { c })
		vim.api.nvim_win_set_buf(right, b)
		vim.wait(200, function() return vim.api.nvim_get_current_win() == left end)
		assert.equals(left, vim.api.nvim_get_current_win())
		assert.equals(b, vim.api.nvim_win_get_buf(left))
		assert.equals(c, vim.api.nvim_win_get_buf(right))
		assert.same({ c }, wg.list(right))
		vim.cmd("only")
		for _, buf in ipairs({ a, b, c }) do vim.api.nvim_buf_delete(buf, { force = true }) end
	end)
end)
